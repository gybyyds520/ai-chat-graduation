CREATE TABLE IF NOT EXISTS payment_record (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL COMMENT '用户ID',
    username VARCHAR(100) COMMENT '用户名',
    payment_type VARCHAR(20) NOT NULL DEFAULT 'UPGRADE' COMMENT '支付类型: UPGRADE/RENEW',
    version_type VARCHAR(20) NOT NULL COMMENT '版本类型: PRO/ENTERPRISE',
    amount DECIMAL(10,2) NOT NULL COMMENT '支付金额',
    duration_days INT NOT NULL COMMENT '购买天数',
    payment_method VARCHAR(50) COMMENT '支付方式',
    transaction_id VARCHAR(100) UNIQUE COMMENT '交易编号',
    payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' COMMENT '支付状态: PENDING/SUCCESS/FAILED',
    review_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' COMMENT '审核状态: PENDING/APPROVED/REJECTED',
    review_remark TEXT COMMENT '审核备注',
    review_time DATETIME COMMENT '审核时间',
    reviewed_by BIGINT COMMENT '审核人ID',
    payment_time DATETIME COMMENT '支付时间',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_user_id (user_id),
    INDEX idx_version_type (version_type),
    INDEX idx_payment_status (payment_status),
    INDEX idx_review_status (review_status),
    INDEX idx_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='充值记录表';